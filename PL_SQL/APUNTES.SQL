DECLARE 
    NOMBRE EMP.ENAME%TYPE;
    
BEGIN

    SELECT ENAME INTO NOMBRE
    FROM EMP
    WHERE EMPNO=&CODIGO;
    DBNS_OUTPUT.PUT_LINE('EL EMPLEADO SE LLAMA' ||NOMBRE);

END;


DECLARE
    DEPAR DEPT%ROWTYPE; -- (SIEMPRE QUE HAYA UN ROWTYPE TIENE QUE HABER OBLIGATORIAMENTE UN * EN LA SELECT ES UN TIPO DE DATO COMPUESTO POCO FLEXIBLE TIENES QUE COJER TODOS LOS CAMPOS DE LA TABLA)


BEGIN    
    SELECT  * INTO DEPAR
    FROM DEPT
    WHERE DEPTNO IN (SELECT DEPTNO FROM EMP WHERE EMPNO=&CODIGO );
    DBMS_OUTPUT.PUT_LINE('CUALQUIER COSA '||DEPAR.LOC)

END;



